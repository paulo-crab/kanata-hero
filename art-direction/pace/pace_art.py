"""Pace: the campus wayfinding system, as in-world signage on the 16 px grid.

Pace has no body, no face and no portrait (design/characters/pace.md). It is a
rounded wayfinding icon plus orderly horizontal bars, drawn as environment
pieces: wall signs, a hanging sign, floor inlays and a standing directory.

Pixels as code: the two icons are hand-placed key grids; every other piece is a
drawing function over the palette keys below. PNG/JSON outputs are generated by
build_pace.py and never hand-edited. Light comes from the upper left, hard
pixels only.

Palette: ink, warm stone, blue glass and brass from STYLE_BIBLE section 3.
Never the violet ramp, never a UI marker hex (#19AFA2 #EC776D #9876D5 #E6B750).
Brass appears as small trim only; its lightest step (#F5D580) is reserved for
glints and is not used at all at present.
"""
import numpy as np

PAL = {
    "o": "#202337", "k": "#343650", "t": "#535971", "a": "#777A8C",   # ink
    "D": "#665D65", "d": "#968A85", "s": "#C7B7A0", "S": "#F0DEC0",   # warm stone
    "F": "#203A50", "f": "#366479", "g": "#5AA3AE", "h": "#A0DDD4",   # blue glass
    "p": "#705056", "b": "#AC7655", "B": "#E1AC62", "y": "#F5D580",   # brass
}
MARKERS = {"#19AFA2", "#EC776D", "#9876D5", "#E6B750"}
VIOLET = {"#413755", "#67547C", "#9477AF", "#C3A6D6"}
# Glint budgets per piece (pixels): lightest brass and lightest glass.
GLINT_LIMITS = {"y": 3, "h": 4}
FLOOR = "#F0DEC0"   # STONE[3], the review-room floor
WALL = "#968A85"    # STONE[1], the review-room wall face


def rgb(k):
    h = PAL[k]
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


# ------------------------------------------------------------------ canvas helpers

def new(w, h):
    return np.zeros((h, w, 4), np.uint8)


def put(a, x, y, k):
    if 0 <= y < a.shape[0] and 0 <= x < a.shape[1]:
        a[y, x] = (*rgb(k), 255)


def clear(a, x, y):
    a[y, x] = 0


def rect(a, x0, y0, x1, y1, k):
    for y in range(y0, y1):
        for x in range(x0, x1):
            put(a, x, y, k)


def grid(a, rows, x0, y0, remap=None):
    """Blit a key grid; '.' is transparent. remap swaps keys (state variants)."""
    for dy, row in enumerate(rows):
        for dx, ch in enumerate(row):
            if ch != ".":
                put(a, x0 + dx, y0 + dy, (remap or {}).get(ch, ch))


def cast(a, x0, x1, y):
    """Two-row contact shadow below a base, like environment.Room.cast."""
    for x in range(x0 + 1, x1 + 1):
        put(a, x, y, "t")
    for x in range(x0 + 2, x1 + 2):
        put(a, x, y + 1, "a")


# ------------------------------------------------------------------ the icon

